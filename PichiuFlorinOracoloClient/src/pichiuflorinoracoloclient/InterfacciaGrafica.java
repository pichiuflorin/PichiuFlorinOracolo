    private ClientConnection client = new ClientConnection();
    
    private void send(String command) {
        if (!client.isConnected()) {
            textArea.append("[Non sei connesso: premi Connettiti]\n");
            return;
        }
        textArea.append("Tu: " + command + "\n");
        client.sendCommand(command);
    }
    
    private void sendQuestion() {
        String text = textField.getText().trim();
        if (text.isEmpty()) {
            return;
        }
        send("/ask " + text);
        if (client.isConnected()) {
            textField.setText("");
        }
    }
    
    private void startReading() {
        new Thread(() -> {
            String line = client.readReply();
            while (line != null) {
                textArea.append("Server: " + line + "\n");
                line = client.readReply();
            }
            btnConnect.setText("Connettiti");
            textArea.append("[Disconnesso]\n");
        }).start();
    }
    
